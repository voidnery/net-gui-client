// Package secrets — шифрование секретов средствами операционной системы
// (мера S6 из ADR-006).
//
// # Что это даёт и чего не даёт
//
// На Windows используется DPAPI в machine scope: ключ шифрования принадлежит
// машине и недоступен для чтения ни одному процессу. Скопированный на другой
// компьютер файл профилей расшифровать нельзя.
//
// ⚠️ Machine scope означает, что расшифровать может ЛЮБОЙ процесс на этой
// машине. Само по себе шифрование не защищает от локального злоумышленника.
// Оно работает в паре с мерой S5: каталог данных службы закрыт на чтение и
// запись непривилегированным пользователям, поэтому до шифротекста ещё нужно
// добраться. Дополнительная энтропия (см. appEntropy) отсекает случайное
// расшифровывание чужими программами, но секретом не является — она лежит в
// исполняемом файле.
//
// Смысл меры в другом: секреты не лежат открытым текстом там, где их увидит
// резервная копия, синхронизация каталога, антивирусный карантин или человек,
// заглянувший в файл.
//
// # Об обнулении памяти
//
// ADR-006 требует «обнуление после использования». Для байтовых буферов это
// выполнимо — см. Zero. Для строк Go — нет: строки неизменяемы, а сборщик
// мусора волен копировать их при перемещении. Поэтому поля профиля, будучи
// строками, гарантированно затереть невозможно.
//
// Требование выполнено в той части, которая достижима, и здесь это сказано
// прямо, чтобы отметка «S6 выполнена» не создавала ложной уверенности.
// Полное решение потребовало бы хранить секреты в []byte на всём пути от
// расшифровки до передачи в ядро — это отдельная переработка, и она уместна
// только если появится модель угроз, где чтение памяти процесса реально.
package secrets

import "errors"

// ErrUnsupported означает, что на этой платформе хранилище секретов ещё не
// реализовано.
//
// Возвращается вместо тихого перехода на открытое хранение намеренно. Молчащий
// откат к плоскому тексту — это то, что попадает в релиз и остаётся навсегда:
// всё работает, никто не замечает. Явная ошибка заставляет реализовать
// платформенное хранилище (для Linux — Secret Service, для macOS — Keychain)
// прежде, чем там появятся пользователи.
var ErrUnsupported = errors.New("secrets: хранилище секретов не реализовано на этой платформе")

// appEntropy — дополнительная энтропия, привязывающая шифротекст к этому
// приложению.
//
// ⚠️ Это НЕ ключ и не секрет: значение находится в исполняемом файле и
// извлекается дизассемблером за минуту. Его роль — сделать так, чтобы блоб,
// зашифрованный нами, не расшифровывался посторонней программой на той же
// машине по случайности или по недосмотру.
var appEntropy = []byte("net-gui-client/profiles/v1")

// Zero затирает содержимое буфера.
//
// Применимо к байтовым срезам, которыми мы владеем: расшифрованный блоб можно
// стереть сразу после того, как значение извлечено. Со строками так нельзя —
// см. замечание в описании пакета.
func Zero(b []byte) {
	for i := range b {
		b[i] = 0
	}
}
