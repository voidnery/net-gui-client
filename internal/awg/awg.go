// Package awg — параметры обфускации AmneziaWG 2.0 и их проверка.
//
// # Где живёт само преобразование
//
// Не здесь, а в форке wireguard-go: net-core/wireguard-go/device/awg.go.
//
// Причина в MAC1. Его область покрытия включает поле типа сообщения:
//
//	mac1 = MAC(HASH(LABEL_MAC1 || Spub_responder), msg[0 : offset_of_mac1])
//
// Поэтому подмена типа обязана происходить ДО вычисления MAC, то есть внутри
// сборки сообщения. Первая реализация делала её снаружи, как преобразование
// UDP-датаграмм, — сервер молча отбрасывал все пакеты. Установлено
// экспериментом E3, подробности в ADR-001.
//
// # Что осталось здесь
//
// Модель параметров и её проверка: они нужны при разборе конфигурации,
// задолго до того как дело дойдёт до сетевого стека. Держать проверку рядом
// с сетевым кодом означало бы узнавать об испорченном файле только при
// попытке подключения.
package awg

import "fmt"

// Размеры сообщений WireGuard. Совпадают с константами
// device/noise-protocol.go эталонной реализации.
const (
	// MessageInitiationSize: тип(4) + отправитель(4) + эфемерный ключ(32) +
	// статический ключ(32+16) + метка времени(12+16) + MAC1(16) + MAC2(16).
	MessageInitiationSize = 148

	// MessageResponseSize: тип(4) + отправитель(4) + получатель(4) +
	// эфемерный ключ(32) + пустое поле(0+16) + MAC1(16) + MAC2(16).
	MessageResponseSize = 92
)

// Config — параметры обфускации AmneziaWG 2.0.
//
// Имена полей совпадают с ключами в файлах .conf, чтобы разбор конфигурации
// читался однозначно и сверялся с исходным файлом глазами.
type Config struct {
	// Jc — количество мусорных пакетов перед первым рукопожатием.
	Jc int
	// Jmin, Jmax — границы случайного размера мусорного пакета, байты.
	Jmin int
	Jmax int

	// S1 — размер случайного дополнения перед пакетом init.
	S1 int
	// S2 — размер случайного дополнения перед пакетом response.
	S2 int

	// H1..H4 — значения, заменяющие стандартные типы сообщений 1..4.
	H1 uint32
	H2 uint32
	H3 uint32
	H4 uint32
}

// IsZero сообщает, что обфускация не настроена: это обычный WireGuard.
func (c Config) IsZero() bool {
	return c == Config{}
}

// Validate проверяет согласованность параметров.
//
// Проверка строгая намеренно. Неверные параметры не дают внятной ошибки во
// время работы — рукопожатие просто не проходит, и пользователь видит
// «сервер недоступен» вместо «конфигурация испорчена».
func (c Config) Validate() error {
	if c.IsZero() {
		return nil // обычный WireGuard без обфускации
	}

	if c.Jc < 0 || c.Jc > 128 {
		return fmt.Errorf("awg: Jc = %d вне допустимого диапазона 0..128", c.Jc)
	}
	if c.Jc > 0 {
		if c.Jmin < 0 || c.Jmax < c.Jmin {
			return fmt.Errorf("awg: некорректный диапазон Jmin=%d, Jmax=%d", c.Jmin, c.Jmax)
		}
		if c.Jmax > 1280 {
			return fmt.Errorf("awg: Jmax = %d превышает разумный размер датаграммы", c.Jmax)
		}
	}
	if c.S1 < 0 || c.S2 < 0 {
		return fmt.Errorf("awg: отрицательное дополнение S1=%d, S2=%d", c.S1, c.S2)
	}

	// ⚠️ Ограничение, вытекающее из способа классификации пакетов на приёме:
	// тип определяется по паре «размер + заголовок». Если S1+148 совпадёт с
	// S2+92, пакеты init и response станут неотличимы по размеру.
	if c.S1+MessageInitiationSize == c.S2+MessageResponseSize {
		return fmt.Errorf(
			"awg: S1+%d совпадает с S2+%d (%d) — пакеты init и response станут неразличимы по размеру",
			MessageInitiationSize, MessageResponseSize, c.S1+MessageInitiationSize)
	}

	// Совпадение заголовков лишает смысла саму подмену и ломает разбор.
	headers := []uint32{c.H1, c.H2, c.H3, c.H4}
	for i := range headers {
		for j := i + 1; j < len(headers); j++ {
			if headers[i] == headers[j] {
				return fmt.Errorf("awg: заголовки H%d и H%d совпадают (%d)", i+1, j+1, headers[i])
			}
		}
	}
	return nil
}
