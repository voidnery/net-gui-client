//go:build !devmode

package main

// devMode выключен в обычных и релизных сборках.
//
// Мера из ADR-006: «режим разработчика с гарантией отсутствия в релизной
// сборке». Гарантия обеспечивается build-тегом, а не проверкой во время
// работы: без тега `devmode` этот файл попадает в сборку, константа равна
// false, и компилятор вырезает весь зависящий от неё код целиком.
//
// Флага командной строки или переменной окружения для включения нет
// намеренно — иначе ослабление проверок было бы доступно на машине
// пользователя, а именно этого мы и избегаем.
const devMode = false
